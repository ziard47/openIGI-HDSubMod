# 1. Update detailed_subtitles/sinhala_detailed.json
det_path = 'detailed_subtitles/sinhala_detailed.json'
with open(det_path, 'r', encoding='utf-8-sig') as f:
    detailed = json.load(f)

for item in detailed:
    cid = item['Id']
    if cid in conversational_map:
        item['Sinhala'] = conversational_map[cid]

with open(det_path, 'w', encoding='utf-8') as f:
    json.dump(detailed, f, ensure_ascii=False, indent=2)
print("Updated detailed_subtitles/sinhala_detailed.json with conversational lines.")

# 2. Build full translations dictionary (keys = English with & without speaker)
trans_dict = {}
for item in detailed:
    eng = item['English']
    sin = item['Sinhala']
    trans_dict[eng] = sin
    
    # Strip speaker prefix if present
    colon_idx = eng.find(': ')
    if 0 < colon_idx <= 15:
        stripped_eng = eng[colon_idx + 2:]
        sin_colon = sin.find(': ')
        if 0 < sin_colon <= 15:
            stripped_sin = sin[sin_colon + 2:]
            trans_dict[stripped_eng] = stripped_sin

# Also save to translations/sinhala_unicode_backup.json
backup_path = 'translations/sinhala_unicode_backup.json'
with open(backup_path, 'w', encoding='utf-8') as f:
    json.dump(trans_dict, f, ensure_ascii=False, indent=2)
print(f"Updated {backup_path} with {len(trans_dict)} entries.")

# 3. Run convert_sinhala.js to convert Unicode -> FM-Abhaya
